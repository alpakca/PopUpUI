namespace PopUpUI.Elements
{
    /// <summary>Presents the visibility of <see cref="PopUpUI.Elements.PopUpElement"/>.</summary>
    public enum Visibility
    {
        /// <summary>Indicates that element can be seen and usable.</summary>
        Visible = 0,
        /// <summary>Indicates that element neither can be seen nor usable.</summary>
        Hidden = 1,
        /// <summary>Indicates that element can't be seen but usable.</summary>
        Unseen = 2
    }
}
