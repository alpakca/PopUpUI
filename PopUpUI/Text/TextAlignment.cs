namespace PopUpUI.Text
{
    /// <summary>Alignment options for rendering text.</summary>
    public enum TextAlignment
    {
        /// <summary>Text appears at top-left position relative to target text will be rendered on.</summary>
        TopLeft,
        /// <summary>Text appears at top-middle position relative to target text will be rendered on.</summary>
        TopMiddle,
        /// <summary>Text appears at top-right position relative to target text will be rendered on.</summary>
        TopRight,

        /// <summary>Text appears at middle-left position relative to target text will be rendered on.</summary>
        MiddleLeft,
        /// <summary>Text appears at center relative to target text will be rendered on.</summary>
        Center,
        /// <summary>Text appears at middle-right position relative to target text will be rendered on.</summary>
        MiddleRight,

        /// <summary>Text appears at bottom-left position relative to target text will be rendered on.</summary>
        BottomLeft,
        /// <summary>Text appears at bottom-middle position relative to target text will be rendered on.</summary>
        BottomMiddle,
        /// <summary>Text appears at bottom-right position relative to target text will be rendered on.</summary>
        BottomRight
    }
}
